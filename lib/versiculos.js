function diaDoAno(d = new Date()) {
  return Math.floor((d - new Date(d.getFullYear(), 0, 0)) / 86400000);
}

/** O versículo de hoje, igual ao que a tela mostra. */
function versiculoDoDia(d = new Date()) {
  const [nr, cap, verso] = VERSICULOS[diaDoAno(d) % VERSICULOS.length];
  return { nr, cap, verso, livro: NOMES[nr] || 'Bíblia' };
}

